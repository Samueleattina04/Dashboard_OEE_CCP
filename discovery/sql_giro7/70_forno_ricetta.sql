-- Giro 7 - FORNOKING500: esiste un campo con ricetta/prodotto/ordine?
-- 1) Valori distinti di FBATCH (= CODICE_ORDINE del PLC) nello storico HIST, con conteggio e periodo.
-- 2) Riga MACCHINE del forno (task e materiale correnti).
-- 3) Task, ordini e situazioni NetPro che citano il forno, con articolo.
SET LOCK_TIMEOUT 5000;
SET NOCOUNT ON;

SELECT ISNULL(NULLIF(LTRIM(RTRIM(FBATCH)), N''), N'(vuoto)') AS fbatch, COUNT(*) AS campioni,
       MIN(FTIMESTAMP) AS primo, MAX(FTIMESTAMP) AS ultimo
FROM dbo.FPROCESSDATA
WHERE FOBJECT = N'FORNOKING500' AND FOBJTYPE = N'MAC' AND FCHANNEL = N'HIST'
GROUP BY ISNULL(NULLIF(LTRIM(RTRIM(FBATCH)), N''), N'(vuoto)')
ORDER BY campioni DESC;

SELECT MACCHINA, DESCRIZIONE, TASK, CODICE_MATERIALE, STATO_FISICO, STATO_LOGICO, FCODE01, FCODE02,
       ORA_ST_FISICO, ORA_ST_LOGICO
FROM dbo.MACCHINE
WHERE MACCHINA = N'FORNOKING500';

SELECT 'TASKS' AS fonte, t.TASK AS codice, t.DESCRIZIONE, t.STATO, t.DATA_INIZIO, t.DATA_FINE,
       o.ORDINE, o.PART_NUMBER, o.DESCRIZIONE AS descrizione_ordine
FROM dbo.TASKS AS t
LEFT JOIN dbo.JOBSET AS j ON j.TASK = t.TASK
LEFT JOIN dbo.ORDINI AS o ON o.ORDINE = j.ORDINE
WHERE t.MACCHINA = N'FORNOKING500' OR t.MACCHINA_ASSEGNATA = N'FORNOKING500'
ORDER BY t.DATA_INIZIO DESC;

SELECT 'SITUAZIONI' AS fonte, TIPO, ISNULL(NULLIF(PART_NUMBER, N''), N'(vuoto)') AS part_number,
       ISNULL(NULLIF(LOTTO, N''), N'(vuoto)') AS lotto, COUNT(*) AS righe, MIN(DATA) AS prima, MAX(DATA) AS ultima
FROM dbo.SITUAZIONI
WHERE MACCHINA = N'FORNOKING500'
GROUP BY TIPO, ISNULL(NULLIF(PART_NUMBER, N''), N'(vuoto)'), ISNULL(NULLIF(LOTTO, N''), N'(vuoto)')
ORDER BY righe DESC;
