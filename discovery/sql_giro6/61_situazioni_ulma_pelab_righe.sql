-- Giro 6 - SITUAZIONI di ULMA e PELAB: tutte le righe (circa 7.000), colonne esplicite.
-- Escluse le colonne con nomi di persone (OPERATORE, SQUADRA).
SET LOCK_TIMEOUT 5000;
SET NOCOUNT ON;

SELECT MACCHINA, OGGETTO, TIPO_OGGETTO, DATA, PROGRESSIVO, TIPO, TURNO,
       ORA_INIZIO, ORA_FINE, LAVORO, LAVORO_GIUST, SETUP, SETUP_GIUST,
       TASK, ID_OPER, PART_NUMBER, LOTTO, CAUSALE, CAUSALE_MAT, FENDCAUSE, CHIUSURA,
       QTA_RICHIESTA, QTA_CICLO, QTA_CONTATA, QTA_COMPLETATA, QTA_SCARTATA, QTA_SOSPESA,
       QUANTITA1, QUANTITA2, QUANTITA3, QUANTITA4,
       INFO01, INFO02, INFO03, INFO04, INFO05, INFORMAZIONI,
       DOCUMENTO, QUADRATURA, FINSDATE, EXPORTDATE
FROM dbo.SITUAZIONI
WHERE MACCHINA IN (N'ULMA', N'PELAB')
ORDER BY MACCHINA, DATA, ORA_INIZIO, PROGRESSIVO;
