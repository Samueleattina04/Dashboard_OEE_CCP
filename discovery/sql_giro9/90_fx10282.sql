-- Giro 9 - FX10282 (nuova selezionatrice Fenix): le colonne di FPROCESSDATA hanno lo stesso significato di FX10130?
-- 1) Ultime 30 righe HIST di FX10282 e, per confronto, di FX10130 (colonne usate dalla dashboard per FX10130).
-- 2) Valori distinti di FVALUE01 (CurrentSmState per FX10130) su tutto lo storico di FX10282.
-- Lettura su indice cluster, poche centinaia di righe.
SET LOCK_TIMEOUT 5000;
SET NOCOUNT ON;

SELECT TOP 30 FOBJECT, CONVERT(varchar(23), FTIMESTAMP, 121) AS FTIMESTAMP, FBATCH,
       FVALUE01, FVALUE02, FVALUE03, FVALUE04, FVALUE05,
       FNVALUE01, FNVALUE02, FNVALUE03, FNVALUE04, FNVALUE05, FNVALUE06,
       FNVALUE07, FNVALUE08, FNVALUE09, FNVALUE10, FNVALUE11, FNVALUE12, FNVALUE13
FROM dbo.FPROCESSDATA
WHERE FOBJECT = N'FX10282' AND FOBJTYPE = N'MAC' AND FCHANNEL = N'HIST'
ORDER BY FTIMESTAMP DESC;

SELECT TOP 30 FOBJECT, CONVERT(varchar(23), FTIMESTAMP, 121) AS FTIMESTAMP, FBATCH,
       FVALUE01, FVALUE02, FVALUE03, FVALUE04, FVALUE05,
       FNVALUE01, FNVALUE02, FNVALUE03, FNVALUE04, FNVALUE05, FNVALUE06,
       FNVALUE07, FNVALUE08, FNVALUE09, FNVALUE10, FNVALUE11, FNVALUE12, FNVALUE13
FROM dbo.FPROCESSDATA
WHERE FOBJECT = N'FX10130' AND FOBJTYPE = N'MAC' AND FCHANNEL = N'HIST'
ORDER BY FTIMESTAMP DESC;

SELECT ISNULL(NULLIF(LTRIM(RTRIM(FVALUE01)), N''), N'(vuoto)') AS fvalue01, COUNT(*) AS campioni,
       MIN(FTIMESTAMP) AS primo, MAX(FTIMESTAMP) AS ultimo
FROM dbo.FPROCESSDATA
WHERE FOBJECT = N'FX10282' AND FOBJTYPE = N'MAC' AND FCHANNEL = N'HIST'
GROUP BY ISNULL(NULLIF(LTRIM(RTRIM(FVALUE01)), N''), N'(vuoto)')
ORDER BY campioni DESC;
